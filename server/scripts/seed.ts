// The marks, two rows above the x-height (y 600 to 800) or under the baseline. On a capital, compose raises them by 200.
const MARKS: Record<string, { bitmap: string; top: number }> = {
  acute: { bitmap: '...#. ..#..', top: 800 }, grave: { bitmap: '.#... ..#..', top: 800 }, circumflex: { bitmap: '..#.. .#.#.', top: 800 },
  dieresis: { bitmap: '.#.#.', top: 700 }, tilde: { bitmap: '.##.# #.##.', top: 800 }, caron: { bitmap: '.#.#. ..#..', top: 800 },
  cedilla: { bitmap: '..#.. .##..', top: 0 }, ring: { bitmap: '..#.. .#.#.', top: 800 },
};

const PIXEL = 100;
const BEARING = 50;

/** The rectangles of a bitmap, one per run of pixels in a row, drawn counterclockwise (y up). */
function pathOf(bitmap: string, start = 700): { path: string; advance: number } {
  const rows = bitmap.split(' ');
  const width = Math.max(...rows.map((row) => row.length));
  const parts: string[] = [];
  rows.forEach((row, index) => {
    const top = start - index * PIXEL;
    for (const run of row.matchAll(/#+/g)) {
      const x0 = BEARING + run.index * PIXEL;
      const x1 = x0 + run[0].length * PIXEL;
      parts.push(`M${x0} ${top - PIXEL}H${x1}V${top}H${x0}Z`);
    }
  });
  return { path: parts.join(''), advance: width * PIXEL + 2 * BEARING };
}

const ops: Record<string, unknown>[] = [{ op: 'set_metrics', metrics: { ascender: 1000, capHeight: 700, xHeight: 500, descender: -200 } }, { op: 'set_glyph', glyph: 'space', advance: 400 }];
for (const [char, bitmap] of Object.entries({ ...UPPER, ...LOWER, ...DIGITS, ...SIGNS, ...EXTRA })) {
  ops.push({ op: 'set_glyph', glyph: recipe(char).name, unicode: char.codePointAt(0), ...pathOf(bitmap) });
}
for (const [name, { bitmap, top }] of Object.entries(MARKS)) ops.push({ op: 'set_glyph', glyph: name, ...pathOf(bitmap, top) });
ops.push({ op: 'compose', chars: 'àâçéèêëîïôùûüÿÀÂÇÉÈÊËÎÏÔÙÛÜŸáíñóúÁÍÑÓÚäöÄÖ' });
const kerns = ['L T', 'L V', 'L Y', 'T a', 'T e', 'T o', 'V a', 'V o', 'Y o'].map((pair) => {
  const [left, right] = pair.split(' ');
  return { op: 'set_kern', left, right, value: -100 };
});

